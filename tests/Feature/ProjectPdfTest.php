<?php

namespace Tests\Feature;

use App\Models\Project;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\View;
use Tests\TestCase;

class ProjectPdfTest extends TestCase
{
    use RefreshDatabase;

    public function test_pdf_requires_an_admin(): void
    {
        $this->get('/admin/projects/pdf')->assertRedirect('/login');
        $this->actingAs(User::factory()->create())
            ->get('/admin/projects/pdf')->assertForbidden();
    }

    public function test_admin_can_stream_pdf_with_database_data_and_images(): void
    {
        $admin = User::factory()->create(['is_admin' => true]);
        foreach (range(1, 11) as $number) {
            Project::create([
                'nama_project' => 'Project '.$number,
                'teknologi' => 'Laravel',
                'description' => 'Deskripsi lengkap project '.$number,
                'status' => 'Active',
                'image' => $number <= 10 ? 'project'.$number.'.jpg' : 'missing.jpg',
            ]);
        }

        $this->actingAs($admin)->get(route('admin.projects.index'))
            ->assertOk()->assertSee(route('admin.projects.pdf'))->assertSee('Cetak PDF');

        $reportProjects = null;
        View::composer('admin.projects.laporan-pdf', function ($view) use (&$reportProjects) {
            $reportProjects = $view->getData()['projects'];
        });
        $response = $this->get(route('admin.projects.pdf'));
        $response->assertOk()->assertHeader('Content-Type', 'application/pdf');
        $this->assertStringContainsString('inline;', $response->headers->get('Content-Disposition'));
        $this->assertStringStartsWith('%PDF-', $response->getContent());

        $this->assertCount(11, $reportProjects);
        $html = view('admin.projects.laporan-pdf', ['projects' => $reportProjects])->render();
        $this->assertStringContainsString('Project 1', $html);
        $this->assertStringContainsString('Project 11', $html);
        $this->assertStringContainsString('Generated by: Kevino Prianda - 241011750132', $html);
        $this->assertStringContainsString('/Subtype /Image', $response->getContent());
    }

    public function test_empty_report_can_be_rendered(): void
    {
        $this->actingAs(User::factory()->create(['is_admin' => true]))
            ->get(route('admin.projects.pdf'))
            ->assertOk()->assertHeader('Content-Type', 'application/pdf');
    }
}
